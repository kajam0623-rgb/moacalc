function axisPos(lo, hi, v, top) {
  if (v >= 1) return 50;
  const sMin = Math.max(0, hi - v), sMax = Math.min(lo, 1 - v);
  const s = sMin <= sMax ? (top ? Math.max(sMin, sMax - 0.02) : (sMin + sMax) / 2) : Math.min(1 - v, Math.max(0, (lo + hi) / 2 - v / 2));
  return Math.round(s / (1 - v) * 100);
}
