/* 천간 오행과 지지 오행의 관계 — 60갑자마다 결이 갈리는 지점.
   생(生): 목→화→토→금→수→목,  극(剋): 목→토→수→화→금→목 */
const EL_ORDER = ["목","화","토","금","수"];
const gen = (a,b) => EL_ORDER[(EL_ORDER.indexOf(a)+1)%5] === b; // a가 b를 생한다
const ke  = (a,b) => EL_ORDER[(EL_ORDER.indexOf(a)+2)%5] === b; // a가 b를 극한다

function relKey(ganEl, jiEl){
  if (ganEl === jiEl)  return "비화";
  if (gen(ganEl, jiEl)) return "설기"; // 천간이 지지를 생 — 내주는 날
  if (gen(jiEl, ganEl)) return "생조"; // 지지가 천간을 생 — 받쳐주는 날
  if (ke(ganEl, jiEl))  return "재";   // 천간이 지지를 극 — 밀어붙이는 날
  return "관";                          // 지지가 천간을 극 — 눌리는 날
}

